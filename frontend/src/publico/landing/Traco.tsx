import type { ReactNode } from "react";

// Ícones de traço da página inicial, no mesmo desenho dos de icones.tsx.
export function Traco({ children, tamanho = 24 }: { children: ReactNode; tamanho?: number }) {
  return (
    <svg
      width={tamanho}
      height={tamanho}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}
